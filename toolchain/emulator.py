def _from_rgb(rgb):
    """translates an rgb tuple of int to a tkinter friendly color code
    """
    return "#%02x%02x%02x" % system_color(rgb)  

# Make a pixel window 254x254 pixels (do NOT call mainloop here)
def make_pixel_window():
    root = tk.Tk()
    root.title("Pixel Window")
    # Create a canvas for pixel drawing (VGA 254x254)
    canvas = tk.Canvas(root, width=254, height=254, bg='black')
    canvas.pack()
    return root, canvas

# Initialize emulator
def init_emulator():
    make_terminal()
    pixel_window, canvas = make_pixel_window()
    return pixel_window, canvas

# load file contents into memory (keep only hex characters)
def load_file_to_memory(filename):
    with open(filename, 'r') as f:
        s = f.read()
    s = re.sub(r'\n', '', s)    
    return s

def get_byte_from_memory(data: str, address: int):
    """Return a byte (0-255) from hex string memory at the specified byte address."""
    num_bytes = len(data) // 2
    if 0 <= address < num_bytes:
        hexstr = data[address*2: address*2 + 2]
        return int(hexstr, 16), address
    else:
        raise IndexError("Address out of bounds")

def execute_instruction_opcodes(data: str, opcode: int, address: int, canvas, pixel_window, x, y):
    # If opcode is 0x95, read next 63 bytes as pixel grayscale values
    if opcode == 0x95:
        # consume the 0x95 opcode + 63 following bytes => advance by 64
        for i in range(63):
            try:
                next_addr = address + i + 1  # +1 to skip the opcode itself
                val, _ = get_byte_from_memory(data, next_addr)
            except IndexError:
                break
            # map single byte to grayscale color, with val (vga 0-255)
            canvas.create_rectangle(x, y, x+1, y+1, fill=_from_rgb(val), outline=_from_rgb(val))
            x += 1
            if x > 252:
                x = 1
                y += 1
            if y > 252:
                y = 1
        pixel_window.update()
        address += 64
    return address, x, y

