# Make a terminal window 80x24 chars (640x480 pixels)
def make_terminal():
    if platform.system() == "Windows":
        os.system("mode con: cols=80 lines=24")
    else:
        # best-effort; harmless if unsupported
        try:
            sys.stdout.write("\x1b[8;24;80t")
        except Exception:
            pass

